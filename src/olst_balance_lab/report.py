"""Write RESULTS.md from results/summary.json values only (aggregates)."""
from __future__ import annotations

from pathlib import Path

LAB = {"window_failure_share": "Window failure share", "tts_s": "Time to stability, s", "first_hold_s": "First attempt stable hold, s",
       "early_touchdown_share": "Early touchdown share (attempts)", "naive_break_share": "Naive t_break share (attempts)",
       "never_stable_share": "Never stable share (attempts)", "hold_s_all_stable_attempts": "Stable hold, all stable attempts, s"}


def _f(x, pct=False):
    if x is None:
        return "NA"
    return f"{x * 100:.1f}%" if pct else f"{x:.2f}"


def _d(x, pct=False):
    if x is None:
        return "NA"
    return f"{x * 100:+.1f} points" if pct else f"{x:+.2f}"


def row(name, v, pct):
    return (f"| {LAB.get(name, name)} | {_f(v['young_mean'], pct)} ({_f(v['young_ci95_low'], pct)} to {_f(v['young_ci95_high'], pct)}) | "
            f"{_f(v['old_mean'], pct)} ({_f(v['old_ci95_low'], pct)} to {_f(v['old_ci95_high'], pct)}) | "
            f"{_d(v['diff_old_minus_young'], pct)} ({_d(v['diff_ci95_low'], pct)} to {_d(v['diff_ci95_high'], pct)}) |")


def comp_table(d: dict) -> list[str]:
    out = ["| Endpoint | Young, mean (95% CI) | Old, mean (95% CI) | Old minus Young (95% CI) |", "|-|-|-|-|"]
    for k, v in d.items():
        out.append(row(k, v, "share" in k))
    return out


def write_results_md(s: dict, path: Path) -> None:
    f = s["audit"]["facts"]
    ps = s["primary_sample"]
    p = s["primary"]
    L = ["# Results", "",
         "Generated by `scripts/run_analysis.py` from the official, hash checked metadata tables. All numbers are aggregates. "
         "Rules: [ANALYSIS_PLAN.md](ANALYSIS_PLAN.md). Task caveat first: this is a yoga tree one-leg stance with arms overhead "
         "inside cued 4 s windows, not the clinical one-leg stand test, and the sample is healthy adults only.", "",
         "## 1. Deposit audit", "",
         "| Flag | Severity | Item | Finding |", "|-|-|-|-|"]
    for k, v in s["audit"]["flags"].items():
        L.append(f"| {k} | {v['severity']} | {v['item']} | {v['finding']} |")
    apc = ", ".join(f"{k} attempts: {v}" for k, v in f["attempts_per_capture"].items())
    L += ["", f"Captures by number of attempts ({apc}). Attempts shorter than 0.5 s from foot lift to end: "
          f"{f['very_short_attempts_under_0_5s']}. Seconds_per_Frame median within person SD: {f['seconds_per_frame_within_person_sd_median']:.5f} s. "
          "Tables `t01` to `t03`; figure `fig01_deposit_audit`.", "",
          "## 2. Primary sample", "",
          f"{ps['definition']}.", "",
          f"People: {ps['young_people']} Young, {ps['old_people']} Old. Windows: {ps['young_windows']} Young, {ps['old_windows']} Old. "
          f"Attempts per window, mean: Young {s['attempts_per_window']['Young']['mean']:.2f}, Old {s['attempts_per_window']['Old']['mean']:.2f} "
          f"(max {s['attempts_per_window']['Young']['max']:.0f} and {s['attempts_per_window']['Old']['max']:.0f}).", "",
          "## 3. Primary result (pre-specified)", "",
          f"CIs: {s['ci_method']}.", ""]
    L += comp_table(p)
    L += ["", "Group medians of the person summaries: " + "; ".join(
        f"{LAB[k]} Young {_f(v['young_median'], 'share' in k)}, Old {_f(v['old_median'], 'share' in k)}" for k, v in p.items()) + ".",
          "Welch t intervals for the difference: " + "; ".join(
        f"{LAB[k]} {_d(v['welch_ci95_low'], 'share' in k)} to {_d(v['welch_ci95_high'], 'share' in k)}" for k, v in p.items()) + ".", "",
          "Same sample, attempt level shares summarised per person:", ""]
    L += comp_table(s["attempt_shares_per_person"])
    L += ["", "The naive t_break share is shown only because the brief listed it. In 4 s cued windows most end of stability "
          "labels are the end cue, so it is not a balance loss measure (flag A9).", "",
          "## 4. Sensitivity analyses", "",
          "S1, all valid short attempts, person cluster bootstrap:", ""]
    L += comp_table(s["sensitivity_S1_attempt_level"])
    for lab, d in s["sensitivity_person_level"].items():
        L += ["", f"{lab}:", ""] + comp_table(d)
    L += ["", "## 5. Stance foot (paired, descriptive)", "",
          "| Group, endpoint | n | Left base | Right base | Left minus right (95% CI) |", "|-|-|-|-|-|"]
    for k, v in s["stance_foot"].items():
        pct = "share" in k
        L.append(f"| {k.replace('|', ', ')} | {v['n_people']} | {_f(v['mean_left_base'], pct)} | {_f(v['mean_right_base'], pct)} | "
                 f"{_d(v['mean_diff_left_minus_right'], pct)} ({_d(v['ci95_low'], pct)} to {_d(v['ci95_high'], pct)}) |")
    L += ["", "Leg dominance was not recorded, so this is left vs right, not dominant vs non dominant.", "",
          "## 6. Balance Self Assessment vs observed (descriptive)", "",
          "| Group, endpoint | n | Spearman rho (95% CI) |", "|-|-|-|"]
    for k, v in s["self_assessment_descriptive"].items():
        L.append(f"| {k.replace('|', ', ')} | {v['n_people']} | {_f(v['spearman_rho'])} ({_f(v['ci95_low'])} to {_f(v['ci95_high'])}) |")
    L += ["", "Self ratings span only 2 to 5 and groups are small; these correlations are descriptive.", "",
          "## 7. Long 20 s captures, Old only (descriptive, separate)", "",
          "| Measure | n | Median | P25 | P75 | Min | Max |", "|-|-|-|-|-|-|-|"]
    for k, v in s["long_old_only_descriptive"].items():
        if v["p25"] is None:
            L.append(f"| {k} (share) | {v['n']} | {_f(v['median'], True)} | | | | |")
        else:
            L.append(f"| {k} | {v['n']} | {_f(v['median'])} | {_f(v['p25'])} | {_f(v['p75'])} | {_f(v['min'])} | {_f(v['max'])} |")
    L += ["", "No Young long captures exist, so these values are never compared with Young and are not clinical OLST times.", "",
          "## 8. Force-plate check of the labels", ""]
    fp = s["forceplate"]
    if fp["status"] == "run":
        L += [f"Run on {fp['captures']} short captures ({fp['files']} verified force-plate CSVs), {fp['attempts']} attempts, {fp['people']} people.", "",
              "| Group | Check | Attempts | People | Value | CI or IQR |", "|-|-|-|-|-|-|"]
        for x in fp["summary"]:
            isshare = not (x["check"].startswith("median") or "minus" in x["check"])
            L.append(f"| {x['group']} | {x['check']} | {x['attempts']} | {x['people']} | {_f(x['share'], isshare)} | "
                     f"{_f(x['ci95_low'], isshare)} to {_f(x['ci95_high'], isshare)} |")
    else:
        L += [f"Skipped: {fp['reason']}. Documented as future work."]
    L += ["", "## Figures", ""]
    for name in s["outputs"]["figures"]:
        if name.endswith(".png"):
            L.append(f"* `figures/{name}` (WebP twin alongside)")
    L += ["", "## Attribution", "", s["dataset"]["citation"] + ". " + s["dataset"]["license"] + ". Also cite PhysioNet: "
          + s["dataset"]["physionet_citation"] + ".", ""]
    path.write_text("\n".join(L), encoding="utf-8")
